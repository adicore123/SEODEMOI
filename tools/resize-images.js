#!/usr/bin/env node
/**
 * resize-images.js — כיווץ סופי עם sharp: hero עד 1600px, גלריה עד 1200px, JPEG q78.
 * מנרמל את כל הקבצים ל-<stem>.jpg, מוחק מקורות בסיומות אחרות, משחזר קובץ שנפגם
 * ובונה מחדש את assets/images.js. הרצה: node tools/resize-images.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const https = require('https');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const IMG_DIR = path.join(ROOT, 'site', 'assets', 'images');

// הקובץ tires/1.jpg נדרס בטעות בבדיקת הרשאות — משחזרים אותו מהמקור
const RECOVER = [[path.join(IMG_DIR, 'tires', '1.jpg'),
  'https://image-search-mcp-cn-beijing.oss-cn-beijing.aliyuncs.com/image-search-mcp/images-ppt/35aea1033f01.jpg']];

function fetchBuf(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { timeout: 30000, headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
      if (res.statusCode !== 200) { res.resume(); return reject(new Error('HTTP ' + res.statusCode)); }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

async function main() {
  const files = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) walk(path.join(dir, e.name));
      else if (/\.(jpe?g|png|webp)$/i.test(e.name)) files.push(path.join(dir, e.name));
    }
  })(IMG_DIR);

  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  let ok = 0, fail = 0;
  for (const f of files) {
    const isHero = path.basename(f, path.extname(f)) === 'hero';
    const maxW = isHero ? 1600 : 1200;
    const target = f.replace(/\.(jpe?g|png|webp)$/i, '') + '.jpg';
    // קריאה ב-fs עם ניסיונות חוזרים (נעילות OneDrive חולפות), ואז עיבוד מבאפר
    let src = null, lastErr = null;
    for (let i = 0; i < 5 && !src; i++) {
      try { src = fs.readFileSync(f); } catch (e) { lastErr = e; await sleep(1200); }
    }
    if (!src) { console.error('FAIL read', path.relative(IMG_DIR, f), lastErr.message); fail++; continue; }
    try {
      const buf = await sharp(src).resize({ width: maxW, withoutEnlargement: true })
        .jpeg({ quality: 78, mozjpeg: true }).toBuffer();
      for (let i = 0; i < 5; i++) {
        try { fs.writeFileSync(target, buf); break; } catch (e) { await sleep(1200); if (i === 4) throw e; }
      }
      if (target !== f) {
        for (let i = 0; i < 5; i++) {
          try { fs.unlinkSync(f); break; } catch (e) { await sleep(1200); if (i === 4) console.error('WARN leftover', path.relative(IMG_DIR, f)); }
        }
      }
      ok++;
    } catch (e) { console.error('FAIL', path.relative(IMG_DIR, f), e.message); fail++; }
    await sleep(150);
  }

  // בניית images.js מהתוכן בפועל
  const images = {};
  for (const slug of fs.readdirSync(IMG_DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    const dir = path.join(IMG_DIR, slug);
    const all = fs.readdirSync(dir).filter((n) => /\.(jpe?g|png|webp)$/i.test(n));
    const hero = all.find((n) => /^hero\./.test(n));
    const gallery = all.filter((n) => /^\d+\./.test(n)).sort((a, b) => parseInt(a) - parseInt(b));
    images[slug] = { hero: `assets/images/${slug}/${hero}`, gallery: gallery.map((g) => `assets/images/${slug}/${g}`) };
  }
  fs.writeFileSync(path.join(ROOT, 'site', 'assets', 'images.js'),
    '// auto-generated by tools/resize-images.js\nwindow.IMAGES = ' + JSON.stringify(images, null, 1) + ';\n');
  console.log(`עובדו ${ok} תמונות (${fail} כשלונות)`);
}
main().catch((e) => { console.error(e); process.exit(1); });
