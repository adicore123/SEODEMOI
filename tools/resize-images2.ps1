# resize-images2.ps1 - lock-safe image resize: read file to memory, process,
# save to temp and swap. Normalizes output to <stem>.jpg (except webp) and
# rebuilds assets/images.js from actual directory contents.
# Run: powershell -ExecutionPolicy Bypass -File tools/resize-images2.ps1

Add-Type -AssemblyName System.Drawing
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$imgDir = Join-Path $root "site\assets\images"

$jpegCodec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() |
    Where-Object { $_.MimeType -eq 'image/jpeg' }

function Save-Jpeg($image, $path, $quality) {
    $ep = New-Object System.Drawing.Imaging.EncoderParameters(1)
    $ep.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter(
        [System.Drawing.Imaging.Encoder]::Quality, [long]$quality)
    $image.Save($path, $jpegCodec, $ep)
}

$count = 0
Get-ChildItem -Path $imgDir -Recurse -Include *.jpg, *.jpeg, *.png | ForEach-Object {
    $file = $_
    $target = Join-Path $file.DirectoryName ($file.BaseName + '.jpg')
    $tmp = $target + '.tmp'
    try {
        $bytes = [System.IO.File]::ReadAllBytes($file.FullName)
        $ms = New-Object System.IO.MemoryStream(,$bytes)
        $img = [System.Drawing.Image]::FromStream($ms)
        $isHero = $file.BaseName -eq 'hero'
        $maxW = if ($isHero) { 1600 } else { 1200 }
        $newW = [Math]::Min($img.Width, $maxW)
        $newH = [int]($img.Height * $newW / $img.Width)
        $bmp = New-Object System.Drawing.Bitmap($newW, $newH)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $g.DrawImage($img, 0, 0, $newW, $newH)
        $g.Dispose(); $img.Dispose(); $ms.Dispose()
        Save-Jpeg $bmp $tmp 78
        $bmp.Dispose()
        Move-Item $tmp $target -Force
        if ($target -ne $file.FullName) { Remove-Item $file.FullName -Force }
        $script:count++
    } catch {
        Write-Output ("FAIL " + $file.FullName + ": " + $_.Exception.Message)
        if (Test-Path $tmp) { Remove-Item $tmp -Force -ErrorAction SilentlyContinue }
    }
}
Write-Output ("processed: " + $count + " files")

$lines = @()
Get-ChildItem -Path $imgDir -Directory | Sort-Object Name | ForEach-Object {
    $slug = $_.Name
    $hero = Get-ChildItem $_.FullName -Filter 'hero.*' | Select-Object -First 1
    $gallery = Get-ChildItem $_.FullName | Where-Object { $_.BaseName -match '^[0-9]+$' } |
        Sort-Object { [int]$_.BaseName }
    if ($null -eq $hero) { Write-Output ("WARN no hero for " + $slug); return }
    $g = ($gallery | ForEach-Object { '"' + ('assets/images/' + $slug + '/' + $_.Name) + '"' }) -join ', '
    $lines += ('  "' + $slug + '": { "hero": "assets/images/' + $slug + '/' + $hero.Name + '", "gallery": [' + $g + '] }')
}
$out = "// auto-generated by tools/resize-images2.ps1`nwindow.IMAGES = {`n" + ($lines -join ",`n") + "`n};`n"
[System.IO.File]::WriteAllText((Join-Path $root "site\assets\images.js"), $out)
Write-Output "images.js rebuilt"
